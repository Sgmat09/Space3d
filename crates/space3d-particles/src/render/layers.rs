//! Render layers: one per sprite layer, ribbon layer and beam layer of every registered effect —
//! its draw parameters (`GpuDrawParams`, a dynamic-offset uniform), its texture and its two rows
//! of the curve LUT (a color row; a row of size / alpha / coverage for sprites, width for
//! ribbons), rebuilt only when the effects change.

use crate::cpu::PackLayer;
use crate::effect::{
    BeamLayer, BuiltinTexture, Facing, FlipbookMode, LUT_WIDTH, ParticleBlend, ParticleLayer, RibbonFacing,
    RibbonLayer, RibbonUv, SortMode, SpriteShape, SpriteTarget, SpriteTexture,
};
use crate::pack::f16_bits;
use crate::registry::{EffectHandle, ParticleEffects};
use space3d_render::TextureHandle;

/// Shape id of textured sprites (`S3dpDraw::mode.z`).
pub(crate) const SHAPE_TEXTURE: u32 = 5;

/// Draw parameters of a render layer (`S3dpDraw` in `particles.wgsl`, 112 bytes).
#[repr(C)]
#[derive(Clone, Copy, Debug, Default, PartialEq, bytemuck::Pod, bytemuck::Zeroable)]
pub(crate) struct GpuDrawParams {
    pub lut: [f32; 4],
    pub mode: [u32; 4],
    pub shape: [f32; 4],
    pub stretch: [f32; 4],
    pub fade: [f32; 4],
    /// Flipbook: frames, atlas columns, atlas rows, mode (0 none, 1 over life, 2 fps, 3 random,
    /// 4 random start + fps).
    pub book: [f32; 4],
    /// Flipbook: cycles or fps, blend (0/1), texture layers, 1 when the instances carry their
    /// age in seconds (rotation and age as two halves).
    pub book2: [f32; 4],
}

/// A texture a layer samples.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub(crate) enum TexKey {
    /// A procedural built-in (generated by the node).
    Builtin(BuiltinTexture),
    /// A texture of the renderer's assets.
    Handle(TextureHandle),
}

/// What a render layer draws.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum LayerKind {
    /// Sprite particles (the instance stream).
    Sprite,
    /// A ribbon layer (strips built from ribbon tracks).
    Ribbon,
    /// A beam layer (strips built from the emitters' beam ends).
    Beam,
}

/// Sorting and drawing facts of a render layer.
#[derive(Clone, Copy, Debug, PartialEq)]
pub(crate) struct LayerInfo {
    pub pack: PackLayer,
    /// Draws into the post distortion buffer (`SpriteTarget::Distortion`) in the Distortion
    /// slot, never in color.
    pub distortion: bool,
    /// Per-particle back-to-front order in each view (`SortMode::ByDistance`): the layer's
    /// emitters draw as one group, sorted per view.
    pub sorted: bool,
    /// `SpriteRender::order` (`RibbonLayer::order`, `BeamLayer::order`).
    pub order: i16,
    /// Additive layers draw after alpha and premultiplied ones of the same order.
    pub additive: bool,
    pub kind: LayerKind,
    /// The texture it samples.
    pub texture: Option<TexKey>,
}

/// First render layer of an effect slot and its sprite, ribbon and beam layer counts.
#[derive(Clone, Copy, Debug)]
struct Base {
    first: u32,
    sprites: u16,
    ribbons: u16,
    beams: u16,
    handle: EffectHandle,
}

/// Every render layer, in effect slot order (an effect's sprite layers, then its ribbons, then
/// its beams).
#[derive(Debug, Default)]
pub(crate) struct RenderLayers {
    /// `ParticleEffects::version` these were built from (`None`: never built).
    pub version: Option<u64>,
    base: Vec<Base>,
    pub params: Vec<GpuDrawParams>,
    pub info: Vec<LayerInfo>,
    /// `Rgba16Float` texels, `LUT_WIDTH` × `rows`.
    pub lut: Vec<u16>,
    pub rows: u32,
    warned_path: bool,
}

fn shape_params(shape: &SpriteShape) -> (u32, [f32; 4]) {
    match *shape {
        SpriteShape::Glow { core, hardness } => (0, [core, hardness.clamp(0.0, 1.0), 0.0, 0.0]),
        SpriteShape::Streak { core, taper } => (1, [core, taper.clamp(0.0, 1.0), 0.0, 0.0]),
        SpriteShape::Ring { thickness, focus, fill } => (2, [thickness, focus.max(0.0), fill, 0.0]),
        SpriteShape::Smoke { breakup, hot_core } => (3, [breakup, hot_core.clamp(0.0, 1.0), 0.0, 0.0]),
        SpriteShape::Vortex { arms, twist } => (4, [arms, twist, 0.0, 0.0]),
        SpriteShape::Texture(_) => (SHAPE_TEXTURE, [0.0; 4]),
    }
}

fn blend_id(b: ParticleBlend) -> u32 {
    match b {
        ParticleBlend::Alpha => 1,
        ParticleBlend::Premultiplied => 2,
        _ => 0,
    }
}

/// Texture layers of a built-in texture.
pub(crate) fn builtin_layers(t: BuiltinTexture) -> u32 {
    match t {
        BuiltinTexture::Fireball16 | BuiltinTexture::Smoke16 => 16,
        _ => 1,
    }
}

impl RenderLayers {
    fn texture_key(&mut self, t: &SpriteTexture, effect: &str) -> Option<TexKey> {
        match t {
            SpriteTexture::Builtin(b) => Some(TexKey::Builtin(*b)),
            SpriteTexture::Handle(h) => Some(TexKey::Handle(*h)),
            SpriteTexture::Path(p) => {
                // With the `assets` feature the plugin resolves paths into handles (the layer
                // draws untextured while the image loads): only a build without it is warned.
                if !cfg!(feature = "assets") && !self.warned_path {
                    self.warned_path = true;
                    tracing::warn!(
                        effect = %effect,
                        path = %p,
                        "particle textures by path are loaded with the `assets` feature and an AssetServer \
                         (until then, or without them, the layer draws untextured): or use \
                         SpriteTexture::Handle (RenderAssets::add_texture) or a built-in"
                    );
                }
                None
            }
        }
    }

    fn push_rows(&mut self, color: impl Fn(f32) -> [f32; 4], curves: impl Fn(f32) -> [f32; 4]) {
        for i in 0..LUT_WIDTH {
            let t = i as f32 / (LUT_WIDTH - 1) as f32;
            self.lut.extend(color(t).map(f16_bits));
        }
        for i in 0..LUT_WIDTH {
            let t = i as f32 / (LUT_WIDTH - 1) as f32;
            self.lut.extend(curves(t).map(f16_bits));
        }
    }

    fn row(&self, r: u32) -> f32 {
        (r as f32 + 0.5) / self.rows as f32
    }

    fn sprite(&mut self, layer: &ParticleLayer, effect: &str) {
        let id = self.params.len() as u32;
        let r = &layer.render;
        let (kind, shape) = shape_params(&r.shape);
        let texture = match &r.shape {
            SpriteShape::Texture(t) => self.texture_key(t, effect),
            _ => None,
        };
        // A texture that cannot be drawn falls back to a soft glow.
        let (kind, shape) = if kind == SHAPE_TEXTURE && texture.is_none() {
            (0, [0.0; 4])
        } else {
            (kind, shape)
        };
        let (facing, stretch) = match r.facing {
            Facing::Camera => (0, [0.0, 1.0, 1.0]),
            Facing::VelocityStretched { scale, min, max } => (1, [scale.max(0.0), min.max(0.0), max.max(min.max(0.0))]),
            Facing::Plane { .. } | Facing::EmitterPlane => (2, [0.0, 1.0, 1.0]),
        };
        let layers = match texture {
            Some(TexKey::Builtin(b)) => builtin_layers(b),
            _ => 0,
        };
        let (book, book2) = match (&r.flipbook, texture) {
            (Some(f), Some(_)) => {
                let (mode, param) = match f.mode {
                    FlipbookMode::OverLife { cycles } => (1.0, cycles.max(0.0)),
                    FlipbookMode::Fps(fps) => (2.0, fps.max(0.0)),
                    FlipbookMode::Random => (3.0, 0.0),
                    FlipbookMode::RandomStartFps(fps) => (4.0, fps.max(0.0)),
                };
                let age = crate::runtime::layer::packs_age(layer);
                (
                    [
                        f.frames.max(1) as f32,
                        f.columns.max(1) as f32,
                        f.rows.max(1) as f32,
                        mode,
                    ],
                    [param, f.blend as u32 as f32, layers as f32, age as u32 as f32],
                )
            }
            _ => ([1.0, 1.0, 1.0, 0.0], [0.0, 0.0, layers as f32, 0.0]),
        };
        let rows = self.params.len() as u32 * 2;
        // Distortion layers: the offset at full opacity (view heights) in `fade.w`; their
        // opacity is the shape's weight whatever the blend (they add into the buffer).
        let (distortion, strength) = match r.target {
            SpriteTarget::Distortion { strength } => (true, strength),
            _ => (false, 0.0),
        };
        let blend = if distortion { 0 } else { blend_id(r.blend) };
        self.params.push(GpuDrawParams {
            lut: [
                self.row(rows),
                self.row(rows + 1),
                layer.intensity,
                layer.aspect.max(1e-3),
            ],
            mode: [blend, facing, kind, 0],
            shape,
            stretch: [stretch[0], stretch[1], stretch[2], r.soft_distance.max(0.0)],
            fade: [r.near_fade.0, r.near_fade.1, r.max_screen_size.max(0.0), strength],
            book,
            book2,
        });
        let extent = 0.5 * layer.size_over_life.max_value().max(0.0) * layer.aspect.max(1.0).max(stretch[2]);
        let additive = r.blend == ParticleBlend::Additive || distortion;
        // Unsorted additive layers and distortion layers (order-independent sums) batch every
        // emitter of the layer into one draw, and so do per-particle sorted layers (one group
        // sorted per view); the others draw per emitter, back to front.
        let sorted = !distortion && r.sort == SortMode::ByDistance;
        let batched = sorted || distortion || (additive && matches!(r.sort, SortMode::Auto | SortMode::None));
        self.info.push(LayerInfo {
            pack: PackLayer { id, batched, extent },
            distortion,
            sorted,
            order: r.order,
            additive,
            kind: LayerKind::Sprite,
            texture,
        });
        // Color row, then (size, alpha, coverage, 0).
        self.push_rows(
            |t| layer.color_over_life.eval(t).to_array(),
            |t| {
                [
                    layer.size_over_life.eval(t),
                    layer.alpha_over_life.eval(t),
                    layer.coverage_over_life.eval(t),
                    0.0,
                ]
            },
        );
    }

    fn strip(&mut self, kind: LayerKind, s: StripParams, texture: Option<TexKey>) {
        let id = self.params.len() as u32;
        let (facing, normal) = match s.facing {
            RibbonFacing::Plane { normal } => (1, normal.normalize_or(space3d_core::glam::Vec3::Y)),
            RibbonFacing::Camera => (0, space3d_core::glam::Vec3::ZERO),
        };
        let layers = match texture {
            Some(TexKey::Builtin(b)) => builtin_layers(b),
            _ => 0,
        };
        let rows = self.params.len() as u32 * 2;
        self.params.push(GpuDrawParams {
            lut: [self.row(rows), self.row(rows + 1), s.intensity, s.width.max(0.0)],
            mode: [blend_id(s.blend), facing, 6, texture.is_some() as u32],
            shape: [s.core, s.hardness.clamp(0.0, 1.0), s.noise.clamp(0.0, 1.0), 0.0],
            stretch: [normal.x, normal.y, normal.z, s.soft.max(0.0)],
            fade: [0.0; 4],
            book: [1.0, 1.0, 1.0, 0.0],
            book2: [0.0, 0.0, layers as f32, 0.0],
        });
        let additive = s.blend == ParticleBlend::Additive;
        self.info.push(LayerInfo {
            pack: PackLayer {
                id,
                batched: additive,
                extent: 0.5 * s.width.max(0.0) * s.width_max.max(1.0),
            },
            distortion: false,
            sorted: false,
            order: s.order,
            additive,
            kind,
            texture,
        });
    }

    fn ribbon(&mut self, r: &RibbonLayer, effect: &str) {
        let texture = r.texture.as_ref().and_then(|t| self.texture_key(t, effect));
        self.strip(
            LayerKind::Ribbon,
            StripParams {
                intensity: r.intensity,
                width: r.width,
                blend: r.blend,
                order: r.order,
                core: r.profile.core,
                hardness: r.profile.hardness,
                noise: r.noise,
                soft: r.soft_distance,
                facing: r.facing,
                width_max: r.width_over_life.max_value(),
            },
            texture,
        );
        // Color over life; (width, 1, 0, 0) over life.
        self.push_rows(
            |t| r.color_over_life.eval(t).to_array(),
            |t| [r.width_over_life.eval(t), 1.0, 0.0, 0.0],
        );
    }

    fn beam(&mut self, b: &BeamLayer, effect: &str) {
        let texture = b.texture.as_ref().and_then(|t| self.texture_key(t, effect));
        self.strip(
            LayerKind::Beam,
            StripParams {
                intensity: b.intensity,
                width: b.width,
                blend: b.blend,
                order: b.order,
                core: b.profile.core,
                hardness: b.profile.hardness,
                noise: b.noise,
                soft: b.soft_distance,
                facing: b.facing,
                width_max: b.start_glow.max(b.end_glow).max(1.0),
            },
            texture,
        );
        // Color along the beam; constant width.
        self.push_rows(|t| b.color.eval(t).to_array(), |_| [1.0, 1.0, 0.0, 0.0]);
    }

    /// Rebuild from `effects` if they changed; returns whether anything was rebuilt.
    pub fn sync(&mut self, effects: &ParticleEffects) -> bool {
        if self.version == Some(effects.version()) {
            return false;
        }
        self.version = Some(effects.version());
        self.base.clear();
        self.params.clear();
        self.info.clear();
        self.lut.clear();
        self.base.resize(
            effects.slot_count(),
            Base {
                first: u32::MAX,
                sprites: 0,
                ribbons: 0,
                beams: 0,
                handle: EffectHandle::INVALID,
            },
        );
        let total: usize = effects
            .iter()
            .map(|(_, e)| e.layers.len() + e.ribbons.len() + e.beams.len())
            .sum();
        self.rows = (total as u32 * 2).max(2);
        for (handle, effect) in effects.iter() {
            self.base[handle.index() as usize] = Base {
                first: self.params.len() as u32,
                sprites: effect.layers.len() as u16,
                ribbons: effect.ribbons.len() as u16,
                beams: effect.beams.len() as u16,
                handle,
            };
            for layer in &effect.layers {
                self.sprite(layer, &effect.name);
            }
            for r in &effect.ribbons {
                self.ribbon(r, &effect.name);
            }
            for b in &effect.beams {
                self.beam(b, &effect.name);
            }
        }
        let texels = (LUT_WIDTH * self.rows * 4) as usize;
        self.lut.resize(texels, 0);
        true
    }

    fn base_of(&self, effect: EffectHandle) -> Option<&Base> {
        self.base.get(effect.index() as usize).filter(|b| b.handle == effect)
    }

    /// The render layer of sprite layer `layer` of `effect` (`None` if the effect is gone or
    /// changed shape).
    pub fn layer(&self, effect: EffectHandle, layer: u16) -> Option<&LayerInfo> {
        let b = self.base_of(effect)?;
        (layer < b.sprites).then(|| self.info.get((b.first + layer as u32) as usize))?
    }

    /// The render layer of ribbon `r` of `effect`.
    pub fn ribbon_layer(&self, effect: EffectHandle, r: u16) -> Option<&LayerInfo> {
        let b = self.base_of(effect)?;
        (r < b.ribbons).then(|| self.info.get((b.first + b.sprites as u32 + r as u32) as usize))?
    }

    /// The render layer of beam `k` of `effect`.
    pub fn beam_layer(&self, effect: EffectHandle, k: u16) -> Option<&LayerInfo> {
        let b = self.base_of(effect)?;
        (k < b.beams).then(|| {
            self.info
                .get((b.first + b.sprites as u32 + b.ribbons as u32 + k as u32) as usize)
        })?
    }

    /// Whether any layer draws strips (ribbons or beams).
    pub fn has_strips(&self) -> bool {
        self.info.iter().any(|l| l.kind != LayerKind::Sprite)
    }
}

/// Draw parameters of a ribbon or beam layer.
struct StripParams {
    intensity: f32,
    width: f32,
    blend: ParticleBlend,
    order: i16,
    core: f32,
    hardness: f32,
    noise: f32,
    soft: f32,
    facing: RibbonFacing,
    /// Largest width multiplier (width curve, end glows).
    width_max: f32,
}

/// The tile length of `RibbonUv::Tile` (`None` for `Stretch`).
pub(crate) fn tile_length(uv: RibbonUv) -> Option<f32> {
    match uv {
        RibbonUv::Tile { length } if length > 0.0 => Some(length),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::curve::{Curve, FadeCurve, Gradient};
    use crate::effect::{ParticleEffect, ParticleLayer, SpriteRender};
    use crate::pack::f16_value;
    use space3d_core::glam::Vec4;

    #[test]
    fn lut_rows_hold_the_curves_at_texel_centers() {
        let mut fx = ParticleEffects::default();
        let layer = ParticleLayer {
            color_over_life: Gradient::linear(Vec4::new(4.0, 0.0, 0.0, 1.0), Vec4::new(0.0, 0.0, 2.0, 0.0)),
            size_over_life: Curve::Linear(1.0, 3.0),
            alpha_over_life: Curve::Preset(FadeCurve::Out),
            coverage_over_life: Curve::Constant(0.5),
            render: SpriteRender {
                blend: ParticleBlend::Premultiplied,
                order: -2,
                ..SpriteRender::default()
            },
            ..ParticleLayer::default()
        };
        let a = fx
            .add(ParticleEffect::new("a").layer(ParticleLayer::default()))
            .unwrap();
        let b = fx.add(ParticleEffect::new("b").layer(layer)).unwrap();
        let mut l = RenderLayers::default();
        assert!(l.sync(&fx));
        assert!(!l.sync(&fx), "unchanged");
        assert_eq!(l.rows, 4);
        assert_eq!(l.lut.len(), (LUT_WIDTH * 4 * 4) as usize);
        let info = *l.layer(b, 0).unwrap();
        assert_eq!(
            (info.pack.id, info.order, info.additive, info.pack.batched),
            (1, -2, false, false)
        );
        assert!(l.layer(a, 0).unwrap().pack.batched, "unsorted additive layers batch");
        assert!(l.layer(b, 1).is_none() && l.layer(EffectHandle::INVALID, 0).is_none());
        let texel = |row: u32, i: u32| {
            let o = ((row * LUT_WIDTH + i) * 4) as usize;
            [0, 1, 2, 3].map(|c| f16_value(l.lut[o + c]))
        };
        assert_eq!(texel(2, 0), [4.0, 0.0, 0.0, 1.0]);
        assert_eq!(texel(2, LUT_WIDTH - 1), [0.0, 0.0, 2.0, 0.0]);
        assert_eq!(texel(3, 0), [1.0, 1.0, 0.5, 0.0]);
        assert_eq!(texel(3, LUT_WIDTH - 1), [3.0, 0.0, 0.5, 0.0]);
        let p = l.params[1];
        assert_eq!((p.lut[0], p.lut[1]), (2.5 / 4.0, 3.5 / 4.0));
        assert_eq!(p.mode[0], 2);
        assert_eq!(info.pack.extent, 1.5, "size curve max 3 × ½");
        fx.remove(a);
        assert!(l.sync(&fx));
        assert!(l.layer(a, 0).is_none(), "removed effects draw nothing");
    }

    /// Ribbons and beams get render layers after the effect's sprite layers, with their rows.
    #[test]
    fn ribbons_and_beams_follow_the_sprite_layers() {
        let mut fx = ParticleEffects::default();
        let e = fx
            .add(
                ParticleEffect::new("mixed")
                    .layer(ParticleLayer::default())
                    .ribbon(RibbonLayer {
                        width: 2.0,
                        width_over_life: Curve::Linear(1.0, 0.0),
                        ..RibbonLayer::default()
                    })
                    .beam(BeamLayer {
                        width: 0.5,
                        blend: ParticleBlend::Alpha,
                        texture: Some(SpriteTexture::Builtin(BuiltinTexture::SoftDot)),
                        ..BeamLayer::default()
                    }),
            )
            .unwrap();
        let mut l = RenderLayers::default();
        l.sync(&fx);
        assert_eq!(l.rows, 6);
        let r = *l.ribbon_layer(e, 0).unwrap();
        let b = *l.beam_layer(e, 0).unwrap();
        assert_eq!((r.pack.id, r.kind, r.pack.batched), (1, LayerKind::Ribbon, true));
        assert_eq!((b.pack.id, b.kind, b.pack.batched), (2, LayerKind::Beam, false));
        assert_eq!(b.texture, Some(TexKey::Builtin(BuiltinTexture::SoftDot)));
        assert!(l.ribbon_layer(e, 1).is_none() && l.beam_layer(e, 1).is_none());
        assert_eq!(l.params[1].lut[3], 2.0);
        assert_eq!(l.params[2].mode, [1, 0, 6, 1]);
        assert!(l.has_strips());
    }
}
