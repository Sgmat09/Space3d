//! Android and iOS entry points.
//!
//! # Android
//!
//! Build the game as a `cdylib` (e.g. with `cargo apk`/`xbuild`, NativeActivity) and export
//! `android_main`; winit's `android-activity` backend calls it on the app's main thread:
//!
//! ```ignore
//! #[cfg(target_os = "android")]
//! #[unsafe(no_mangle)]
//! fn android_main(app: space3d_platform::AndroidApp) {
//!     space3d_platform::android_main_entry(app, |app| {
//!         app.add_plugin(space3d_platform::PlatformPlugin::default());
//!         // add game plugins/systems here
//!     });
//! }
//! ```
//!
//! On suspend the native window is destroyed: the runner drops the wgpu surface
//! ([`space3d_render::Renderer::remove_surface`]) and recreates it on resume; the device,
//! meshes and textures survive. Touch input arrives as multi-touch [`crate::Touch`]es.
//!
//! # iOS
//!
//! winit's UIKit backend needs no special entry point in Rust: `space3d::main!` makes the game
//! binary's `main` run the app, and `space3d build --target ios` bundles that binary as an
//! `.app` (see `docs/platforms.md`). An Xcode project can instead link a `staticlib` and call
//! the exported `start_app()` (also generated by `space3d::main!`) from its `main.m`; it never
//! returns:
//!
//! ```ignore
//! #[unsafe(no_mangle)]
//! pub extern "C" fn start_app() {
//!     let mut app = space3d_core::App::new();
//!     app.add_plugin(space3d_platform::PlatformPlugin::default());
//!     app.run();
//! }
//! ```
//!
//! Either way the app uses the **UIScene life cycle**, which apps built with the iOS 27 SDK
//! must adopt (UIKit stops apps without it at launch). The runner defines a scene delegate
//! class, [`IOS_SCENE_DELEGATE_CLASS`], and shows the game's window in the scene it connects;
//! the app's `Info.plist` must name that class:
//!
//! ```xml
//! <key>UIApplicationSceneManifest</key>
//! <dict>
//!   <key>UIApplicationSupportsMultipleScenes</key><false/>
//!   <key>UISceneConfigurations</key>
//!   <dict>
//!     <key>UIWindowSceneSessionRoleApplication</key>
//!     <array><dict>
//!       <key>UISceneConfigurationName</key><string>Default Configuration</string>
//!       <key>UISceneDelegateClassName</key><string>Space3dSceneDelegate</string>
//!     </dict></array>
//!   </dict>
//! </dict>
//! ```
//!
//! Suspend/resume behave as on Android (surface dropped while inactive, recreated on resume).

/// Objective-C class name of the iOS scene delegate the runner registers; the
/// `UISceneDelegateClassName` of the app's `Info.plist` scene configuration must be exactly
/// this (see the [module docs](self)).
pub const IOS_SCENE_DELEGATE_CLASS: &str = "Space3dSceneDelegate";

#[cfg(target_os = "android")]
pub use winit::platform::android::activity::AndroidApp;

#[cfg(target_os = "android")]
static ANDROID_APP: std::sync::OnceLock<AndroidApp> = std::sync::OnceLock::new();

/// Android entry: stash the [`AndroidApp`] for the event loop, build the [`space3d_core::App`]
/// with `build`, then run it.
#[cfg(target_os = "android")]
pub fn android_main_entry(android_app: AndroidApp, build: impl FnOnce(&mut space3d_core::App)) {
    let _ = ANDROID_APP.set(android_app);
    let mut app = space3d_core::App::new();
    build(&mut app);
    app.run();
}

#[cfg(target_os = "android")]
pub(crate) fn android_app() -> Option<AndroidApp> {
    ANDROID_APP.get().cloned()
}
