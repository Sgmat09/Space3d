//! Prelude policy (graphics spec §2.2.10, §2.7): the graphics upgrade adds exactly eight names
//! to `space3d_render::prelude` (and so to `space3d::prelude`), checked against every type and
//! constant name of SpaceCorps2027 at 4159bb8 (`fixtures/game_names_4159bb8.txt`, 793 names). A
//! game glob-importing both the facade prelude and its own modules must never hit an ambiguity.
//! Particles are never in the facade prelude (the game has `Particle`, `Effect`, `Fade`, `Trail`).
#![cfg(feature = "render")]

const GAME_NAMES: &str = include_str!("fixtures/game_names_4159bb8.txt");

/// The prelude additions of the graphics upgrade.
const NEW_PRELUDE_NAMES: [&str; 8] = [
    "PostProcess",
    "Tonemapper",
    "Bloom",
    "CameraFrame",
    "Skybox",
    "EnvironmentLight",
    "DirectionalShadow",
    "CubemapHandle",
];

#[test]
fn new_prelude_names_are_not_game_names() {
    let game: Vec<&str> = GAME_NAMES.lines().map(str::trim).filter(|l| !l.is_empty()).collect();
    assert_eq!(game.len(), 793, "fixture intact");
    for name in NEW_PRELUDE_NAMES {
        assert!(
            !game.contains(&name),
            "`{name}` would be ambiguous with the game's own `{name}`"
        );
    }
}

