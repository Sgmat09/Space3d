/// `use space3d::prelude::*;` and a glob of the game's names side by side: every new prelude
/// name must resolve (an ambiguity is a compile error here).
mod both_globs {
    // Brings every game name into scope: unused unless it makes a prelude name ambiguous.
    #[allow(unused_imports)]
    use super::fixture::*;
    use space3d::prelude::*;

    #[test]
    fn new_prelude_names_resolve() {
        let names = [
            std::any::type_name::<PostProcess>(),
            std::any::type_name::<Tonemapper>(),
            std::any::type_name::<Bloom>(),
            std::any::type_name::<CameraFrame>(),
            std::any::type_name::<Skybox>(),
            std::any::type_name::<EnvironmentLight>(),
            std::any::type_name::<DirectionalShadow>(),
            std::any::type_name::<CubemapHandle>(),
        ];
        for (n, expected) in names.iter().zip(super::NEW_PRELUDE_NAMES) {
            assert!(n.starts_with("space3d_render::") && n.ends_with(expected), "{n}");
        }
        // The prelude's graphics types are usable as written in the docs.
        let post = PostProcess::default()
            .with_tonemapper(Tonemapper::AgX)
            .with_bloom(Bloom::glow());
        assert!(post.enabled);
        assert_eq!(CameraFrame::default().render_scale, None);
        assert_eq!(DirectionalShadow::default().map_size, 2048);
    }
}

